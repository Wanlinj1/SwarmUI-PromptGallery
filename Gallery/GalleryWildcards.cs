using Newtonsoft.Json.Linq;
using SwarmUI.Utils;
using System.IO;

namespace PromptGallery;

/// <summary>Keeps Swarm wildcard files in sync with gallery folders, so a folder can be used as <c>&lt;wildcard:promptgallery/(profile)/(folder)&gt;</c>.
/// Each folder becomes one wildcard file holding the text of every card in it and in its subfolders, one per line.
/// The <c>promptgallery</c> subfolder of Swarm's wildcards folder is owned by this extension and rewritten on every change.</summary>
public static class GalleryWildcards
{
    public const string RootName = "promptgallery";

    static readonly object SyncLock = new();

    /// <summary>Folder that holds the generated wildcard files.</summary>
    public static string Root => Path.Combine(WildcardsHelper.Folder, RootName);

    /// <summary>Wildcard-safe version of a path segment: a comma would end the name inside the tag, so it's replaced.</summary>
    static string SafeSegment(string segment) => segment.Replace(',', ' ').Replace("  ", " ").Trim();

    /// <summary>The wildcard name (as used in the prompt tag) for a folder of a profile.</summary>
    public static string WildcardName(string profile, string folder) =>
        string.Join('/', new[] { RootName, profile }.Concat(folder.Split('/', StringSplitOptions.RemoveEmptyEntries)).Select(SafeSegment));

    /// <summary>Turns card text into one wildcard line: whitespace runs (line breaks included) become one space,
    /// and '#' is dropped since Swarm reads it as the start of a comment.</summary>
    static string ToLine(string prompt) =>
        string.Join(' ', prompt.Replace('#', ' ').Split((char[])null, StringSplitOptions.RemoveEmptyEntries));

    /// <summary>Rewrites the wildcard files of a profile from its cards, removing files of deleted folders. Errors are logged, never thrown.</summary>
    public static void SyncProfile(string profile)
    {
        try
        {
            lock (SyncLock)
            {
                JObject data = GalleryStore.ListCards(profile);
                string name = data["profile"]["name"].ToString();
                List<string> folders = [.. data["folders"].Select(f => f.ToString())];
                List<(string Path, string Line)> cards = [.. data["cards"].Select(c => (c["path"].ToString(), ToLine(c["prompt"].ToString()))).Where(c => c.Item2.Length > 0)];
                Dictionary<string, string> wanted = new(StringComparer.OrdinalIgnoreCase);
                foreach (string folder in folders)
                {
                    string prefix = folder + "/";
                    List<string> lines = [.. cards.Where(c => c.Path.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)).Select(c => c.Line).Distinct()];
                    if (lines.Count == 0)
                    {
                        continue;
                    }
                    string header = $"# Generated by Prompt Gallery from profile '{name}', folder '{folder}' (with subfolders). Edits here are overwritten, edit the cards instead.";
                    wanted[WildcardName(name, folder)] = header.Replace('\n', ' ') + "\n" + string.Join("\n", lines) + "\n";
                }
                string profileDir = Path.Combine(Root, SafeSegment(name));
                foreach ((string wildcard, string content) in wanted)
                {
                    string file = Path.Combine(WildcardsHelper.Folder, wildcard + ".txt");
                    if (File.Exists(file) && File.ReadAllText(file) == content)
                    {
                        continue;
                    }
                    Directory.CreateDirectory(Path.GetDirectoryName(file));
                    File.WriteAllText(file, content, GalleryStore.Utf8NoBom);
                    // A fresh entry makes Swarm re-read the file on next use (it caches options per entry).
                    WildcardsHelper.WildcardFiles[wildcard.ToLowerInvariant()] = new WildcardsHelper.Wildcard() { Name = wildcard };
                }
                if (Directory.Exists(profileDir))
                {
                    foreach (string file in Directory.EnumerateFiles(profileDir, "*.txt", SearchOption.AllDirectories).ToList())
                    {
                        string wildcard = $"{RootName}/" + Path.GetRelativePath(Root, file).Replace('\\', '/')[..^4];
                        if (!wanted.ContainsKey(wildcard))
                        {
                            File.Delete(file);
                            WildcardsHelper.WildcardFiles.TryRemove(wildcard.ToLowerInvariant(), out _);
                        }
                    }
                    DeleteEmptyDirs(profileDir);
                }
            }
        }
        catch (Exception ex)
        {
            Logs.Warning($"[PromptGallery] Failed to update wildcards for profile '{profile}': {ex.Message}");
        }
    }

    /// <summary>Removes the wildcard files of a profile that was deleted or renamed.</summary>
    public static void RemoveProfile(string profile)
    {
        try
        {
            lock (SyncLock)
            {
                string dir = Path.Combine(Root, SafeSegment(profile));
                if (!Directory.Exists(dir) || !(Path.GetFullPath(dir) + Path.DirectorySeparatorChar).StartsWith(Path.GetFullPath(Root) + Path.DirectorySeparatorChar))
                {
                    return;
                }
                Directory.Delete(dir, true);
                string prefix = $"{RootName}/{SafeSegment(profile)}/".ToLowerInvariant();
                foreach (string key in WildcardsHelper.WildcardFiles.Keys.Where(k => k.StartsWith(prefix)).ToList())
                {
                    WildcardsHelper.WildcardFiles.TryRemove(key, out _);
                }
            }
        }
        catch (Exception ex)
        {
            Logs.Warning($"[PromptGallery] Failed to remove wildcards of profile '{profile}': {ex.Message}");
        }
    }

    /// <summary>Syncs every profile, and drops generated files of profiles that no longer exist. Run at startup to pick up edits made on disk.</summary>
    public static void SyncAll()
    {
        List<string> profiles = [.. GalleryStore.ListProfiles().Select(p => p["name"].ToString())];
        foreach (string profile in profiles)
        {
            SyncProfile(profile);
        }
        if (Directory.Exists(Root))
        {
            HashSet<string> live = new(profiles.Select(SafeSegment), StringComparer.OrdinalIgnoreCase);
            foreach (string dir in Directory.EnumerateDirectories(Root).ToList())
            {
                if (!live.Contains(Path.GetFileName(dir)))
                {
                    RemoveProfile(Path.GetFileName(dir));
                }
            }
        }
    }

    static void DeleteEmptyDirs(string dir)
    {
        foreach (string sub in Directory.EnumerateDirectories(dir).ToList())
        {
            DeleteEmptyDirs(sub);
        }
        if (!Directory.EnumerateFileSystemEntries(dir).Any())
        {
            Directory.Delete(dir);
        }
    }
}
